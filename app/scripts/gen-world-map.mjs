// One-off generator: converts world-atlas 110m land topology into a single
// SVG path string using d3-geo's equirectangular projection, so the app can
// render a world map at runtime with zero mapping-library dependency.
import { geoPath, geoEquirectangular } from "d3-geo"
import { feature } from "topojson-client"
import { presimplify, simplify } from "topojson-simplify"
import worldData from "world-atlas/land-110m.json" with { type: "json" }
import { writeFileSync } from "node:fs"

const WIDTH = 980
const HEIGHT = 500

const projection = geoEquirectangular()
  .scale(WIDTH / (2 * Math.PI))
  .translate([WIDTH / 2, HEIGHT / 2])

// This map is decorative (a beacon backdrop), not a reference map — simplify
// heavily and truncate coordinate precision to keep the embedded path small.
const simplified = simplify(presimplify(worldData), 0.15)
const path = geoPath(projection).digits(1)
const land = feature(simplified, simplified.objects.land)
const d = path(land)

const scale = projection.scale()
const translate = projection.translate()

const out = `// Generated by scripts/gen-world-map.mjs from world-atlas (110m land, public domain / ODbL).
// Do not hand-edit. Re-run the script to regenerate.

export const WORLD_MAP_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}"
export const WORLD_MAP_WIDTH = ${WIDTH}
export const WORLD_MAP_HEIGHT = ${HEIGHT}

export const WORLD_MAP_PATH = "${d}"

// Matches the equirectangular projection used to generate the path above —
// use this to plot any lat/lon onto the same ${WIDTH}x${HEIGHT} viewBox.
export function projectLatLon(lat: number, lon: number): [number, number] {
  const scale = ${scale}
  const [tx, ty] = [${translate[0]}, ${translate[1]}]
  const x = tx + ((lon * Math.PI) / 180) * scale
  const y = ty - ((lat * Math.PI) / 180) * scale
  return [x, y]
}
`

writeFileSync(new URL("../components/marketing/world-map-data.ts", import.meta.url), out)
console.log("wrote world-map-data.ts, path length:", d.length)
